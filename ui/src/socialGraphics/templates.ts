const scenes: Record<SocialGraphicsTemplateId, SocialGraphicsScene> = {
  'informed-design-event': informedDesignEventScene,
  'operational-snapshot': operationalSnapshotScene,
  'decision-support-focus': decisionSupportFocusScene,
  'educational-slide': educationalSlideScene,
}

export function createSceneFromTemplate(templateId: SocialGraphicsTemplateId): SocialGraphicsScene {
  return cloneScene(scenes[templateId])
}

export function getGraphicsTemplateOptions(mode: GraphicsWorkspaceMode): SocialGraphicsTemplateOption[] {
  return templateOptions.filter((option) => templateModeMap[option.id] === mode)
}

export function getDefaultTemplateId(mode: GraphicsWorkspaceMode): SocialGraphicsTemplateId {
  const match = templateOptions.find((option) => templateModeMap[option.id] === mode)
  return match?.id ?? (mode === 'social' ? 'educational-slide' : 'operational-snapshot')
}

export function templateBelongsToMode(
  templateId: SocialGraphicsTemplateId,
  mode: GraphicsWorkspaceMode,
): boolean {
  return templateModeMap[templateId] === mode
}

export function graphicsTemplateLabel(templateId: SocialGraphicsTemplateId): string {
  return templateLabelMap[templateId]
}
