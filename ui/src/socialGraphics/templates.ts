function cloneScene(scene: SocialGraphicsScene): SocialGraphicsScene {
  return JSON.parse(JSON.stringify(scene)) as SocialGraphicsScene
}

function buildScene(
  templateId: SocialGraphicsTemplateId,
  title: string,
  elements: SocialGraphicsElement[],
): SocialGraphicsScene {
  return {
    version: 'social-graphics-v1',
    title,
    templateId,
    width: SOCIAL_GRAPHICS_WIDTH,
    height: SOCIAL_GRAPHICS_HEIGHT,
    elements,
  }
}

function background(fill: string): SocialGraphicsElement {
  return {
    id: 'background',
    name: 'Background',
    kind: 'rect',
    x: 0,
    y: 0,
    width: SOCIAL_GRAPHICS_WIDTH,
    height: SOCIAL_GRAPHICS_HEIGHT,
    visible: true,
    opacity: 1,
    fill,
    cornerRadius: 0,
  }
}

function buildBackgroundImage(): SocialGraphicsElement {
  return {
    id: 'background-image',
    name: 'Background Image',
    kind: 'image',
    x: 0,
    y: 0,
    width: SOCIAL_GRAPHICS_WIDTH,
    height: SOCIAL_GRAPHICS_HEIGHT,
    visible: false,
    opacity: 1,
    src: '',
    fit: 'cover',
    cornerRadius: 0,
    assetRole: 'background',
    linkedAssetId: null,
  }
}

function buildLogo(x = 1540, y = 72, width = 240, height = 240): SocialGraphicsElement {
  return {
    id: 'logo',
    name: 'Logo',
    kind: 'image',
    x,
    y,
    width,
    height,
    visible: true,
    opacity: 1,
    src: '/NOAA_logo.png',
    fit: 'contain',
    cornerRadius: 0,
    assetRole: 'logo',
    linkedAssetId: 'noaa-brand-mark',
  }
}

